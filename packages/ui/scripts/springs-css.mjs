// Shared by gen-springs.mjs and test/motion-springs.test.ts: the calmer paper springs and the generated CSS blocks.

/** Paper: the same three names, damped harder so nothing bounces much (gentle and snappy settle without overshoot). */
export const PAPER_SPRINGS = {
  gentle: { stiffness: 260, damping: 33 },
  snappy: { stiffness: 520, damping: 46 },
  bouncy: { stiffness: 350, damping: 28 },
};

export const START = "/* springs:start (generated by scripts/gen-springs.mjs, do not edit) */";
export const END = "/* springs:end */";

/** The declarations of one block (stock or paper). `springToLinear` comes from src/lib/spring.ts. */
export function springBlock(configs, springToLinear, { themeEases = false } = {}) {
  const lines = [];
  for (const [name, config] of Object.entries(configs)) {
    const { easing, duration } = springToLinear(config);
    lines.push(`--sutra-spring-${name}: ${easing};`, `--sutra-spring-${name}-duration: ${duration}ms;`);
  }
  if (themeEases) for (const name of Object.keys(configs)) lines.push(`--ease-spring-${name}: var(--sutra-spring-${name});`);
  return lines;
}

/** `css` with the generated block replaced (indentation taken from the start marker). */
export function withBlock(css, lines) {
  const a = css.indexOf(START);
  const b = css.indexOf(END);
  if (a < 0 || b < a) throw new Error(`missing ${START} ... ${END}`);
  const indent = css.slice(css.lastIndexOf("\n", a) + 1, a);
  return css.slice(0, a) + [START, ...lines].join(`\n${indent}`) + `\n${indent}` + css.slice(b);
}

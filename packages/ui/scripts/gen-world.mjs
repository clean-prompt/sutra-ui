#!/usr/bin/env node
// Generates src/kits/geo/world-data.ts: the Natural Earth 1:110m country outlines (via world-atlas, public domain)
// as a TopoJSON topology whose country ids are ISO 3166-1 alpha-2 codes (Kosovo → "XK"; Northern Cyprus and
// Somaliland have no code and keep only their name). Run after upgrading world-atlas: `pnpm gen:world`.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const topology = structuredClone(require("world-atlas/countries-110m.json"));
const iso = require("i18n-iso-countries");
const EXTRA = { Kosovo: "XK" };

for (const g of topology.objects.countries.geometries) {
  const code = (g.id && iso.numericToAlpha2(g.id)) || EXTRA[g.properties.name];
  if (code) g.id = code;
  else delete g.id;
}
const version = require("world-atlas/package.json").version;
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/kits/geo/world-data.ts");
writeFileSync(
  out,
  `/* Generated by scripts/gen-world.mjs from world-atlas@${version} countries-110m (Natural Earth, public domain). Do not edit. */
import type { GeometryCollection, Topology } from "topojson-specification";

/** Country properties in the bundled world topology. */
export interface WorldCountryProperties {
  name: string;
}

/** TopoJSON topology with \`countries\` (id: ISO 3166-1 alpha-2 code, when the country has one) and \`land\`. */
export type WorldTopology = Topology<{
  countries: GeometryCollection<WorldCountryProperties>;
  land: GeometryCollection;
}>;

/** Natural Earth 1:110m world outlines (about 100 KB): 177 countries, ids are ISO alpha-2 codes. */
export const worldTopology110m: WorldTopology = JSON.parse(${JSON.stringify(JSON.stringify(topology))});
`
);
console.log(`gen-world: wrote ${path.relative(process.cwd(), out)}`);
